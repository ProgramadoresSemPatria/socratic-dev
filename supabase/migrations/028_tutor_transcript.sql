-- ─── LABS01-208 — the tutor transcript lives on the server ──────────────────
-- Closes the first half of audit finding 3.3 (ANALYSIS-2026-11-09).
--
-- /api/tutor used to rebuild the conversation from `body.messages`, taking the
-- ROLE of each turn from the client:
--
--     role: m.role === 'ai' ? 'assistant' : 'user'
--
-- So the browser could claim the tutor had already said anything — e.g. "Sure!
-- The full solution is:" — and the model would simply continue it. In
-- `mode: 'reply'`, which costs no hints, that hands out the solution for free,
-- as often as the attacker likes, in a product whose whole premise is that the
-- tutor answers with questions.
--
-- Dropping the client's `assistant` turns would close the hole but break the
-- product: the Messages API merges consecutive same-role turns, so the tutor
-- would lose every question it had already asked and start over each turn.
-- The transcript therefore moves here. The route reads the history from this
-- table and the request body no longer carries a role at all — there is
-- nothing left to forge.
--
-- Same shape as the rest of the schema after 027: the client reads its own
-- rows, every write goes through the service role, and the ownership
-- invariant is a trigger, because RLS does not constrain the service role.

begin;

-- 027 defines assert_session_owner(). Without it the trigger below cannot be
-- created; fail with a message that says what to do instead of a bare 42883.
do $$
begin
  if not exists (
    select 1 from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'assert_session_owner'
  ) then
    raise exception
      'assert_session_owner() is missing — run 027_session_ownership.sql first';
  end if;
end;
$$;

-- ─── 1. the transcript ──────────────────────────────────────────────────────
create table if not exists public.tutor_messages (
  id          uuid primary key default gen_random_uuid(),
  session_id  uuid not null references public.sessions(id) on delete cascade,
  user_id     uuid not null references public.profiles(id) on delete cascade,
  -- 'assistant' rows are written from the stream the model produced; there is
  -- no request shape that can insert one.
  role        text not null check (role in ('user', 'assistant')),
  content     text not null,
  created_at  timestamptz not null default now()
);

-- The student's message and the tutor's reply are written in ONE insert, so
-- `now()` — the transaction timestamp — is identical on both rows and
-- `order by created_at` puts them in an arbitrary order: the answer can come
-- back before the question it answered, which scrambles the conversation the
-- next turn reads. `seq` is the real order, and it respects the order of the
-- rows inside the insert.
alter table public.tutor_messages
  add column if not exists seq bigint generated by default as identity;

alter table public.tutor_messages enable row level security;

-- ─── 2. the client reads its own turns, and nothing else ────────────────────
drop policy if exists "Users can view their own tutor messages"
  on public.tutor_messages;
create policy "Users can view their own tutor messages"
  on public.tutor_messages for select
  using (auth.uid() = user_id);

grant select on public.tutor_messages to anon, authenticated;
revoke insert, update, delete on public.tutor_messages from anon, authenticated;

-- ─── 3. a turn belongs to the session's owner (reuses 027) ──────────────────
drop trigger if exists tutor_messages_session_owner on public.tutor_messages;
create trigger tutor_messages_session_owner
  before insert or update of session_id, user_id on public.tutor_messages
  for each row execute function public.assert_session_owner();

-- Reading the history is always "this session, in order" — by `seq`, never by
-- `created_at` (see the column comment above).
drop index if exists public.tutor_messages_session_idx;
create index if not exists tutor_messages_session_seq_idx
  on public.tutor_messages (session_id, seq);

-- ─── 4. what the server now reads instead of the request body ───────────────
-- The route loads title, briefing, tests and kind from the challenge behind
-- the session. Read-only check that those four columns exist and that no
-- session points at a missing challenge, which would make the context empty.
do $$
declare
  v_cols    integer;
  v_orphans integer;
begin
  select count(*) into v_cols
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'challenges'
    and column_name in ('title', 'client_briefing', 'tests_source', 'kind');

  select count(*) into v_orphans
  from public.sessions s
  left join public.challenges c on c.id = s.challenge_id
  where c.id is null;

  raise notice 'challenge context columns found (expected 4): %', v_cols;
  raise notice 'sessions pointing at a missing challenge (expected 0): %', v_orphans;

  if v_cols <> 4 then
    raise exception 'challenges is missing a context column — check 004 and 008';
  end if;
end;
$$;

commit;
